#!/usr/bin/env python3
"""Fail on Periphery findings that BuildTools/periphery-baseline.txt does not list.

Usage: python3 -I scripts/check-periphery-baseline.py [--write] SCAN_JSON ...

Each SCAN_JSON is a Periphery JSON scan, such as the two that
.claude/skills/removing-dead-code/scripts/periphery_scan.sh writes. The baseline lists
the known findings by USR, which stays the same when code moves. The check fails on
every finding in product code whose USRs the baseline does not list. It lists findings
in test code, the test targets and ClawTestSupport, without failing on them: product
code comes first. It also names the entries that no scan reports any more; they do not
fail the check.

--write replaces the baseline with the product-code findings of the scans: it adds new
ones to the backlog and drops the entries whose code is gone. Before adding a finding,
delete the code or, for an intentional seam or contract, mark it
`// periphery:ignore - reason`.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from typing import NamedTuple

BASELINE = "BuildTools/periphery-baseline.txt"
# Test code, as periphery_scan.sh's scan without tests excludes it.
TEST_CODE = ("Tests/", "Sources/ClawTestSupport/")
HEADER = """\
# Periphery findings in product code kept as backlog; the dead-code workflow fails on
# any other finding in product code.
# Each entry is a USR, and its comment names the declaration. Generated by
# `scripts/check-periphery-baseline.py --write`, whose usage notes say when to add one.
"""


class Finding(NamedTuple):
    """One result of a Periphery JSON scan."""

    location: str  # path:line:column
    kind: str
    name: str
    hint: str
    ids: tuple[str, ...]  # the declaration's USRs

    @property
    def path(self) -> str:
        """The file that declares it."""
        return self.location.rsplit(":", 2)[0]

    def __str__(self) -> str:
        """Return the finding as a compiler-style location and description."""
        return f"{self.location}: {self.hint}: {self.kind} '{self.name}'"


def read_findings(paths: list[Path]) -> list[Finding]:
    """Read Periphery JSON scans; a declaration both report counts once."""
    by_ids: dict[tuple[str, ...], Finding] = {}
    for path in paths:
        with path.open(encoding="utf-8") as scan:
            for result in json.load(scan):
                finding = Finding(
                    location=result["location"],
                    kind=result["kind"],
                    name=result["name"],
                    hint=",".join(result["hints"]),
                    ids=tuple(result["ids"]),
                )
                by_ids.setdefault(finding.ids, finding)
    return sorted(by_ids.values())


def read_baseline() -> set[str]:
    """Return the USRs the baseline lists; each entry's first word is one."""
    lines = Path(BASELINE).read_text(encoding="utf-8").splitlines()
    return {
        line.split()[0] for line in lines if line.strip() and not line.startswith("#")
    }


def write_baseline(findings: list[Finding]) -> None:
    """Replace the baseline with one entry per USR of the findings, grouped by file."""
    entries = sorted(
        (finding.path, finding.name, usr, finding.kind)
        for finding in findings
        for usr in finding.ids
    )
    lines = [f"{usr}  # {path}: {kind} {name}\n" for path, name, usr, kind in entries]
    Path(BASELINE).write_text(HEADER + "".join(lines), encoding="utf-8")


def parse_arguments() -> argparse.Namespace:
    """Parse the command line."""
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--write", action="store_true", help="replace the baseline with the findings"
    )
    parser.add_argument("scans", nargs="+", type=Path, help="Periphery JSON scans")
    return parser.parse_args()


def main() -> int:
    """Compare the scans with the baseline and return the exit status."""
    arguments = parse_arguments()
    scans = [scan.resolve() for scan in arguments.scans]
    os.chdir(Path(__file__).resolve().parents[1])
    findings = read_findings(scans)
    in_tests = [finding for finding in findings if finding.path.startswith(TEST_CODE)]
    findings = [finding for finding in findings if finding not in in_tests]

    if arguments.write:
        write_baseline(findings)
        print(f"{BASELINE}: {len(findings)} findings")
        return 0

    if in_tests:
        print(f"{len(in_tests)} findings in test code, listed but not checked:")
        print("".join(f"  {finding}\n" for finding in in_tests), end="")
    known = read_baseline()
    new = [finding for finding in findings if known.isdisjoint(finding.ids)]
    for finding in new:
        print(
            f"{finding.location}: error: {finding.hint}: {finding.kind} "
            f"'{finding.name}' is not in {BASELINE}",
            file=sys.stderr,
        )
    reported = {usr for finding in findings for usr in finding.ids}
    stale = sorted(known - reported)
    if stale:
        print(f"{len(stale)} entries in {BASELINE} match no finding any more:")
        print("".join(f"  {usr}\n" for usr in stale), end="")
    if new:
        print(
            f"{len(new)} new findings. Delete the code, mark an intentional seam or "
            "contract `// periphery:ignore - reason`, or record it as backlog with "
            "--write.",
            file=sys.stderr,
        )
    return 1 if new else 0


if __name__ == "__main__":
    sys.exit(main())
